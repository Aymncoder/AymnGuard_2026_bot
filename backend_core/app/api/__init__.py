# ==============================================================================
@api_router.get(
    "/",
    summary="نبض النظام العالمي ومؤشر الاستجابة الذكية",
    tags=["Global System Status"]
)
async def global_api_pulse():
    """
    نقطة وصول فورية (Zero-Latency) تعمل كنبض حي للنظام العصبي.
    تُستخدم هذه النقطة بواسطة أدوات المراقبة العالمية (مثل Docker Healthchecks 
    أو AWS Load Balancers) للتحقق الفوري من:
    - جاهزية المحركات اللوجستية والخوادم.
    - استقرار طبقة الذكاء الاصطناعي العميقة.
    - التوقيت السيادي المتزامن مع العمليات الآلية في الخلفية.
    """
    logger.debug("🌐 [API Gateway]: تم طلب فحص النبض العالمي للنظام بنجاح.")
    
    return {
        "system": "AymnGuard Enterprise Core",
        "status": "ONLINE",
        "ai_engine_status": "ACTIVE",
        "autonomy_level": "Level 5 (Full Autonomy - No Human Intervention)",
        "timestamp": datetime.utcnow().isoformat() + "Z",
        "message": "البوابة العالمية جاهزة، النواة الذكية تعمل بكامل طاقتها الاستيعابية."
    }


# ==============================================================================
# 3. دمج الإصدارات وتوجيه حركة المرور (Traffic Routing & Versioning)
# ==============================================================================
# ربط النسخة الأولى (v1) بالبوابة العظمى.
# سيتم توجيه جميع الطلبات التي تبدأ بـ /v1 إلى نظام الإرشاد والتسويق والخدمات.
api_router.include_router(
    api_v1_router,
    prefix="/v1"
)

